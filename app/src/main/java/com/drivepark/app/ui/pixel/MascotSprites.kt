    private fun with(vararg rows: Pair<Int, String>): PixelSprite {
        val out = BLOB.toMutableList()
        rows.forEach { (y, overlay) ->
            out[y] = buildString { for (x in 0 until 32) append(if (overlay[x] != '.') overlay[x] else out[y][x]) }
        }
        return PixelSprite(out)
    }

